// Token Radar, model radar-2.
//
// One sealed snapshot in, one ranked board out. The snapshot is DefiLlama's
// protocol index as of 2026-11-14: 758 protocols, a 40-protocol watchlist at
// a $50M TVL floor. Nothing here is fetched, guessed, or hand-picked: every
// number below is computed from the snapshot's own ten fields per protocol.
//
// WHAT COUNTS AS A LAUNCH CANDIDATE
// A protocol is rankable only when it records no token at all (no market
// cap, no CoinGecko id, no symbol) AND it is not a product of a token that
// already trades. That second half is where the starter was wrong: it ranked
// WBTC, Binance staked ETH and the big bridges as "pre-token" launches, when
// each is a wrapped, staked or bridged form of something already trading.
// The exclusion below is the watchlist's own rule, applied to the whole
// board: excluded categories (Bridge, Canonical Bridge, Liquid Staking,
// Liquid Restaking, Restaked BTC, CEX), versioned names (a trailing V2 /
// 2.0), names carrying a whole word wrapped / staked / staking, and names
// beginning with an exchange's name. On this snapshot that leaves 198
// rankable protocols: the 40 watchlist rows plus 158 below the floor.
//
// THE VALUE MODEL (radar-2)
//   implied = round( tvl_usd x 0.20 x growthMult x maturityMult )
//
//   base multiple 0.20 — the median market-cap / TVL ratio of the 129
//     live-token protocols in this snapshot that record a market cap
//     (quartiles 0.04 / 0.20 / 1.04). A launch is priced the way the market
//     already prices live protocols of the same kind, not by an invented
//     multiple. The dashboard states this and shows the quartiles.
//   growthMult = 1 + clamp(change_7d, -60, 120) / 100 x 0.75
//     Seven-day TVL growth, clamped so one hot week cannot crown a
//     protocol and one bad week cannot bury it. A missing change_7d is
//     read as 0: no growth signal, no penalty.
//   maturityMult = 0.55 + 0.45 x (1 - exp(-age_days / 540))
//     Age is days since DefiLlama first listed the protocol: how long it
//     has run with no token. The curve saturates — a protocol that has
//     survived three years with no token is mature, not three times as
//     valuable as a one-year-old — and a protocol with no listed date is
//     scored at 365 days, the middle of the watchlist's age range.
// No protocol name is ever special-cased. The same function scores every
// row, and the dashboard recomputes each row from the same figures, so the
// page and board.json always agree.
//
// FARM PLANS
// Seven steps per protocol, generated from its category, chains, TVL and
// age — never from a list of names. Each step states what to do, what it
// costs and how long it takes, and the last step is always the exit: how to
// unwind, and the warning never to pay to claim.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_halflife_days: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.2,
  growth_weight: 0.75,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.55,
  maturity_range: 0.45,
  maturity_halflife_days: 540,
  unknown_age_days: 365,
};

export const MODEL_VERSION = 'radar-2';

/** Live-token protocols shown apart, by market cap. */
export const LIVE_ROWS = 24;

/** Median mcap/TVL of live-token protocols in the snapshot, with quartiles. */
export const COMPARABLES = { p25: 0.04, median: 0.2, p75: 1.04, n: 129 };

